"""Generate a demo monorepo to try pg-launch-check on.

    python examples/make_demo.py demo-pg-app
    pg-launch-check scan demo-pg-app/before
    pg-launch-check scan demo-pg-app/after

`before/` and `after/` contain the same small "shop" monorepo, built from tests/fixtures:

    supabase/migrations/   Supabase SQL migrations (profiles, products, orders, order_items)
    web/                   Next.js + Prisma (schema.prisma, Prisma migrations, route handlers)
    api/                   Express + node-postgres + Drizzle (drizzle-kit migrations)
    worker/                FastAPI + SQLAlchemy + psycopg, and a Django app

`before/` has the mistakes this tool looks for; `after/` does the same work correctly and must
produce no findings. Scan the two folders separately: each one is a whole project with its own
schema. Nothing in it is ever run, it connects to nothing and it contains no real credentials.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIXTURES = HERE.parent / "tests" / "fixtures"

LAYOUT = {
    "before": {"": "sql_vulnerable", "web": "prisma_vulnerable", "api": "node_vulnerable",
               "worker": "py_vulnerable"},
    "after": {"": "sql_clean", "web": "prisma_clean", "api": "node_clean", "worker": "py_clean"},
}

README = """# demo-pg-app

Generated by pg-launch-check's examples/make_demo.py.

    pg-launch-check scan before   # Postgres performance and safety mistakes
    pg-launch-check scan after    # the same monorepo done right: no findings

Each folder holds Supabase SQL migrations (supabase/migrations), a Next.js + Prisma app (web),
an Express + node-postgres + Drizzle API (api) and a FastAPI / SQLAlchemy / Django worker
(worker).
"""


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    out = Path(argv[1])
    if out.exists() and any(out.iterdir()):
        print(f"error: {out} exists and is not empty", file=sys.stderr)
        return 2
    for side, parts in LAYOUT.items():
        for sub, fixture in parts.items():
            src = FIXTURES / fixture
            dst = out / side / sub if sub else out / side
            shutil.copytree(src, dst, dirs_exist_ok=True, ignore=shutil.ignore_patterns("__pycache__"))
    (out / "README.md").write_text(README, encoding="utf-8")
    print(f"Demo project written to {out}. Now run:\n"
          f"  pg-launch-check scan {out / 'before'}\n"
          f"  pg-launch-check scan {out / 'after'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
