"""Finding model and the rule catalogue (ids, titles, why it matters, exact fixes).

Each rule has one fix text per variant ("sql", "prisma", "node-pg", "django", ...). A finding
shows only the fix for the ORM / driver / migration tool it was found in, with its own table,
column and variable names filled in."""

from __future__ import annotations

import re
import textwrap
from dataclasses import asdict, dataclass, field

SEVERITIES = ("critical", "high", "medium", "low", "info")
SEVERITY_RANK = {name: i for i, name in enumerate(SEVERITIES)}  # lower = worse

VARIANT_LABELS = {
    "sql": "SQL migration",
    "prisma": "Prisma",
    "prisma-migrate": "Prisma Migrate",
    "drizzle": "Drizzle",
    "node-pg": "node-postgres (pg)",
    "postgres-js": "postgres.js",
    "knex": "Knex",
    "sqlalchemy": "SQLAlchemy",
    "django": "Django ORM",
    "django-fk": "Django ForeignKey / OneToOne in a loop",
    "django-rev": "Django reverse relation / ManyToMany in a loop",
    "psycopg": "psycopg / psycopg2",
    "asyncpg": "asyncpg",
    "fk": "FOREIGN KEY",
    "check": "CHECK",
    "unique": "UNIQUE",
    "pk": "PRIMARY KEY",
    "type": "ALTER COLUMN TYPE",
    "add": "ADD COLUMN",
    "set": "SET NOT NULL",
    "partitioned": "Partitioned table",
    "default": "Any stack",
}


@dataclass(frozen=True)
class Rule:
    id: str
    title: str
    why: str
    fixes: dict
    heuristic: bool = False

    @property
    def fix(self) -> str:
        """Every variant, for `pg-launch-check rules`."""
        if list(self.fixes) == ["default"]:
            return self.fixes["default"]
        parts = []
        for key, text in self.fixes.items():
            label = VARIANT_LABELS.get(key, key)
            parts.append(f"[{label}]\n" + textwrap.indent(text, "  "))
        return "\n".join(parts)


RULES: dict[str, Rule] = {}


def _rule(id: str, title: str, why: str, fixes: dict[str, str], heuristic: bool = False) -> None:
    RULES[id] = Rule(id, title, " ".join(why.split()),
                     {k: textwrap.dedent(v).strip("\n") for k, v in fixes.items()}, heuristic)


CONCURRENTLY_NOTE = """\
CONCURRENTLY cannot run inside a transaction block: keep the statement alone in its own
migration file and make sure the migration tool does not wrap that file in BEGIN/COMMIT
(several statements sent as one query string also run as one implicit transaction). If the
build fails it leaves an INVALID index behind: DROP INDEX CONCURRENTLY <index>; then retry."""

# ---------------------------------------------------------------- PGL001
_rule(
    "PGL001",
    "Foreign key column without an index",
    """
PostgreSQL creates an index for PRIMARY KEY and UNIQUE constraints, but not for the
referencing column(s) of a FOREIGN KEY. Without one, every DELETE (or key UPDATE) on the
referenced table has to scan the referencing table to check or cascade matching rows, and
joins and filters on the column (WHERE user_id = $1, the usual access path) scan it too. It is
invisible on small tables and turns into slow deletes, long lock waits and slow pages as the
table grows.
""",
    {
        "sql": """
            CREATE INDEX CONCURRENTLY IF NOT EXISTS <index> ON <table> (<cols>);

            Put it alone in a new migration: CONCURRENTLY cannot run inside a transaction block.
            (If <table> is created in the same migration and still empty, a plain CREATE INDEX
            next to the CREATE TABLE is fine.)
        """,
        "prisma": """
            Add an index on the relation scalar field(s) in model <model>:

              model <model> {
                ...
                @@index([<fields>])
              }

            Then `npx prisma migrate dev --create-only`. If the table already holds data, change the
            generated CREATE INDEX to CREATE INDEX CONCURRENTLY and keep it alone in that migration.sql.
        """,
        "sqlalchemy": """
            ForeignKey() does not create an index. Ask for one on the column:

              <field>: Mapped[int] = mapped_column(ForeignKey("..."), index=True)

            With Alembic, check that the autogenerated migration contains op.create_index(...); on a
            table that already holds data, create it with postgresql_concurrently=True inside
            `with op.get_context().autocommit_block():`.
        """,
    },
)

# ---------------------------------------------------------------- PGL002
_rule(
    "PGL002",
    "CREATE INDEX without CONCURRENTLY on an existing table",
    """
A plain CREATE INDEX holds a SHARE lock on the table for the whole build: reads continue,
but every INSERT, UPDATE and DELETE on the table waits until the index is finished, which on a
large table means minutes of failed or stuck writes. CREATE INDEX CONCURRENTLY builds the index
without blocking writes (it takes longer and scans the table twice).
""",
    {
        "sql": "<stmt>\n\n"
               + CONCURRENTLY_NOTE,
        "prisma-migrate": "<stmt>\n\n"
                          + CONCURRENTLY_NOTE + """

Prisma Migrate: create the migration with `npx prisma migrate dev --create-only`, edit its
migration.sql so the CONCURRENTLY statement is the only statement in it, then apply it.""",
        "drizzle": "<stmt>\n\n"
                   + CONCURRENTLY_NOTE + """

drizzle-orm's migrate() applies pending migrations inside a transaction, where CONCURRENTLY
fails: remove the statement from the generated migration and run it as a separate step,
e.g. psql "$DATABASE_URL" -c 'CREATE INDEX CONCURRENTLY ...'.""",
        "partitioned": """
            CONCURRENTLY is not supported on a partitioned table. Build it per partition instead:

              CREATE INDEX <index> ON ONLY <table> (...);              -- instant, invalid until attached
              CREATE INDEX CONCURRENTLY <index>_p1 ON <table>_p1 (...);   -- for each partition
              ALTER INDEX <index> ATTACH PARTITION <index>_p1;
        """,
    },
)

# ---------------------------------------------------------------- PGL003
_rule(
    "PGL003",
    "Constraint added with a full check while holding a lock",
    """
Adding a CHECK constraint to an existing table checks every row while holding an ACCESS
EXCLUSIVE lock (no reads or writes). Adding a FOREIGN KEY checks every row while holding a
lock that blocks writes on both tables. Adding a UNIQUE or PRIMARY KEY constraint builds its
index while holding an ACCESS EXCLUSIVE lock. Adding the constraint as NOT VALID and
validating it separately, or building the index concurrently first, keeps the locked part
instant.
""",
    {
        "fk": """
            ALTER TABLE <table> ADD <constraint_src> NOT VALID;   -- instant; new rows are checked from now on
            ALTER TABLE <table> VALIDATE CONSTRAINT <constraint>;   -- checks existing rows, does not block reads or writes

            Run VALIDATE in a separate migration (or after a COMMIT) so the first lock is released
            right away.
        """,
        "check": """
            ALTER TABLE <table> ADD <constraint_src> NOT VALID;   -- instant; new rows are checked from now on
            ALTER TABLE <table> VALIDATE CONSTRAINT <constraint>;   -- checks existing rows, does not block reads or writes

            Run VALIDATE in a separate migration (or after a COMMIT) so the first lock is released
            right away.
        """,
        "unique": """
            CREATE UNIQUE INDEX CONCURRENTLY <constraint> ON <table> (<cols>);   -- alone in its migration
            ALTER TABLE <table> ADD CONSTRAINT <constraint> UNIQUE USING INDEX <constraint>;   -- instant

            CONCURRENTLY cannot run inside a transaction block (see PGL002).
        """,
        "pk": """
            CREATE UNIQUE INDEX CONCURRENTLY <constraint> ON <table> (<cols>);   -- alone in its migration
            ALTER TABLE <table> ADD CONSTRAINT <constraint> PRIMARY KEY USING INDEX <constraint>;

            The columns must already be NOT NULL, otherwise this step scans the table to set it
            (see PGL005 for the lock-free way). CONCURRENTLY cannot run inside a transaction block.
        """,
    },
)

# ---------------------------------------------------------------- PGL004
_rule(
    "PGL004",
    "Table rewrite while holding an ACCESS EXCLUSIVE lock",
    """
Some ALTER TABLE forms rewrite every row of the table (and rebuild all its indexes) while
holding an ACCESS EXCLUSIVE lock, which blocks all reads and writes until the rewrite is done:
changing a column's type (except binary-compatible changes such as varchar(n) to a longer
varchar or to text), and adding a column whose value must be computed per row (a volatile
default such as gen_random_uuid(), random() or clock_timestamp(), a serial or identity column,
or a stored generated column). Since PostgreSQL 11, adding a column with a constant or stable
default (now() included) is instant and is not reported.
""",
    {
        "type": """
            Don't change the type in place on a large table. Expand and contract instead:

              ALTER TABLE <table> ADD COLUMN <col>_new <type>;            -- instant
              -- backfill in batches, and keep new writes in sync (app double-write or a trigger):
              UPDATE <table> SET <col>_new = <col>::<type> WHERE id BETWEEN 1 AND 10000;   -- repeat
              -- switch reads and writes to <col>_new, then:
              ALTER TABLE <table> DROP COLUMN <col>;
              ALTER TABLE <table> RENAME COLUMN <col>_new TO <col>;

            Changes that do not rewrite: varchar(n) -> varchar(m) with m >= n, varchar -> text,
            numeric(p,s) -> numeric(q,s) with q >= p.
        """,
        "add": """
            Add the column without the per-row default, set the default for new rows, then
            backfill existing rows in batches:

              ALTER TABLE <table> ADD COLUMN <col> <type>;                    -- instant
              ALTER TABLE <table> ALTER COLUMN <col> SET DEFAULT <default>;   -- instant, new rows only
              UPDATE <table> SET <col> = <default>
                WHERE ctid IN (SELECT ctid FROM <table> WHERE <col> IS NULL LIMIT 10000);   -- repeat until 0 rows

            Add NOT NULL afterwards with the lock-free sequence from PGL005.
        """,
    },
)

# ---------------------------------------------------------------- PGL005
_rule(
    "PGL005",
    "NOT NULL added to an existing table",
    """
ADD COLUMN ... NOT NULL without a DEFAULT fails with "column contains null values" on any
table that already has rows, so a migration that worked on an empty development database
breaks the production deploy. ALTER COLUMN ... SET NOT NULL scans the whole table under an
ACCESS EXCLUSIVE lock (no reads or writes) to prove there are no NULLs, unless a validated
CHECK (col IS NOT NULL) constraint already proves it (PostgreSQL 12+).
""",
    {
        "add": """
            Give it a constant default (instant on PostgreSQL 11+):

              ALTER TABLE <table> ADD COLUMN <col> <type> NOT NULL DEFAULT <value>;

            or add it nullable, backfill it in batches, then add NOT NULL without a long lock:

              ALTER TABLE <table> ADD COLUMN <col> <type>;
              -- backfill, then:
              ALTER TABLE <table> ADD CONSTRAINT <table>_<col>_not_null CHECK (<col> IS NOT NULL) NOT VALID;
              ALTER TABLE <table> VALIDATE CONSTRAINT <table>_<col>_not_null;
              ALTER TABLE <table> ALTER COLUMN <col> SET NOT NULL;   -- PG 12+: uses the CHECK, no scan
              ALTER TABLE <table> DROP CONSTRAINT <table>_<col>_not_null;
        """,
        "set": """
            ALTER TABLE <table> ADD CONSTRAINT <table>_<col>_not_null CHECK (<col> IS NOT NULL) NOT VALID;  -- instant
            ALTER TABLE <table> VALIDATE CONSTRAINT <table>_<col>_not_null;   -- scans without blocking reads or writes
            ALTER TABLE <table> ALTER COLUMN <col> SET NOT NULL;              -- PG 12+: uses the CHECK, no scan
            ALTER TABLE <table> DROP CONSTRAINT <table>_<col>_not_null;
        """,
    },
)

# ---------------------------------------------------------------- PGL006
_rule(
    "PGL006",
    "Migration without lock_timeout",
    """
Every ALTER TABLE, and CREATE INDEX without CONCURRENTLY, must acquire a lock on the table.
If a long query or an idle-in-transaction session holds a conflicting lock, the migration
waits, and every new query on that table queues behind the waiting migration: even a change
that takes milliseconds can stall all traffic to the table until the old transaction ends. A
lock_timeout makes the migration give up quickly (you retry it) instead of taking the app down.
""",
    {
        "sql": """
            Start the migration with:

              SET lock_timeout = '5s';

            and retry the migration if it times out. (A statement_timeout also bounds lock waits, but
            a value long enough for a big migration is too long to protect traffic.) A lock_timeout
            set on the migration role (ALTER ROLE ... SET lock_timeout) works too; this tool cannot
            see role settings, so silence the rule with --disable PGL006 if you use one.
        """,
    },
)

# ---------------------------------------------------------------- PGL007
_rule(
    "PGL007",
    "Table without a primary key",
    """
Without a primary key, rows have no stable identity: duplicates slip in, ORMs and admin tools
cannot reliably update or delete one row, and logical replication (used by CDC tools, some
read-replica and upgrade setups, and Supabase Realtime) cannot publish UPDATE and DELETE for
the table unless a replica identity is configured.
""",
    {
        "sql": """
            New table: give it a key in the CREATE TABLE:

              id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

            For a join table, make the pair the key: PRIMARY KEY (<cols>).
            For an existing large table, build the index first, then attach it:

              CREATE UNIQUE INDEX CONCURRENTLY <table>_pkey ON <table> (<cols>);
              ALTER TABLE <table> ADD CONSTRAINT <table>_pkey PRIMARY KEY USING INDEX <table>_pkey;
        """,
        "prisma": """
            Give model <model> an id:

              id Int @id @default(autoincrement())

            or, for a join model, a compound id: @@id([<fields>]).
        """,
    },
)

# ---------------------------------------------------------------- PGL008
_rule(
    "PGL008",
    "UUID primary key stored as text",
    """
A UUID stored as text or varchar takes 37 bytes (36 characters plus a length byte) instead of
16 bytes for the uuid type, so the primary key, every foreign key that copies it, and every
index on them are more than twice as large; comparisons are collation-aware text comparisons
instead of fixed-width ones; and malformed values are accepted.
""",
    {
        "sql": """
            New table:

              <col> uuid PRIMARY KEY DEFAULT gen_random_uuid(),   -- built in since PostgreSQL 13

            Existing table: converting the column (and every foreign key pointing at it) rewrites the
            tables, so plan it as an expand-and-contract migration (see PGL004).
        """,
        "prisma": """
            Store it as a native uuid:

              <field> String @id @default(uuid()) @db.Uuid

            Changing an existing column rewrites the table and its foreign keys: plan the migration
            (see PGL004) instead of applying the generated ALTER COLUMN TYPE directly.
        """,
    },
)

# ---------------------------------------------------------------- PGL009
_rule(
    "PGL009",
    "Money stored as a floating-point type",
    """
real and double precision are binary floating point: 0.1 + 0.2 is not 0.3, sums of many
amounts drift by fractions of a cent, and equality checks on totals fail. Money needs exact
arithmetic: numeric with a fixed scale, or an integer count of the smallest currency unit
(cents).
""",
    {
        "sql": """
            New table:  <col> numeric(12, 2)    (or <col>_cents bigint)

            Existing table: add a numeric column, backfill it with round(<col>::numeric, 2) in batches,
            switch the app to it, then drop the old column (an in-place ALTER COLUMN TYPE rewrites
            the table, see PGL004).
        """,
        "prisma": """
            <field> Decimal @db.Decimal(12, 2)    // Prisma returns Decimal objects

            or store cents as Int / BigInt.
        """,
        "sqlalchemy": """
            <field> = mapped_column(Numeric(12, 2))    # returns decimal.Decimal

            or store cents as Integer / BigInteger.
        """,
        "django": """
            <field> = models.DecimalField(max_digits=12, decimal_places=2)

            or store cents as models.BigIntegerField().
        """,
    },
    heuristic=True,
)

# ---------------------------------------------------------------- PGL010
_rule(
    "PGL010",
    "timestamp without time zone",
    """
timestamp (without time zone) stores a wall-clock reading with no zone: the same instant
written by servers or sessions with different TimeZone settings is stored differently, and
comparisons with now() (a timestamptz) depend on the session's TimeZone. timestamptz stores an
absolute instant (normalised to UTC) in the same 8 bytes, which is what "when did this happen"
columns need.
""",
    {
        "sql": """
            New columns:  <col> timestamptz NOT NULL DEFAULT now()

            Existing columns holding UTC values:

              SET TimeZone = 'UTC';
              ALTER TABLE <table> ALTER COLUMN <col> TYPE timestamptz;
              -- PostgreSQL 12+ skips the table rewrite for this change when the session TimeZone is UTC
        """,
        "prisma": """
            <field> DateTime @default(now()) @db.Timestamptz(3)

            (Prisma maps DateTime to timestamp(3) without time zone unless you add @db.Timestamptz.)
        """,
        "sqlalchemy": """
            <field> = mapped_column(DateTime(timezone=True), server_default=func.now())
        """,
    },
)

# ---------------------------------------------------------------- PGL011
_rule(
    "PGL011",
    "SQL built from strings (SQL injection)",
    """
Pasting values into the SQL text (template literals, f-strings, + concatenation, % or
.format) lets any value that reaches the query change it: a quote in a name or a search box
becomes SQL injection (read, change or delete other users' data). With placeholders the driver
sends the values separately from the query text, so they can never be parsed as SQL. This is a
security issue as much as a database one.
""",
    {
        "node-pg": """
            Pass values as parameters:

              await <recv>.query("SELECT ... WHERE email = $1 AND org_id = $2", [email, orgId]);

            Table and column names cannot be parameters: pick them from a fixed allow-list
            (e.g. const col = { name: "name", date: "created_at" }[req.query.sort]).
        """,
        "prisma": """
            Use the tagged template (interpolated values become parameters):

              await prisma.$queryRaw`SELECT ... WHERE email = ${email}`;

            or keep $queryRawUnsafe / $executeRawUnsafe with $1 placeholders and the values as extra
            arguments: prisma.$queryRawUnsafe("SELECT ... WHERE email = $1", email).
        """,
        "drizzle": """
            Use the sql tag (interpolated values become parameters) instead of sql.raw():

              await db.execute(sql`SELECT ... WHERE email = ${email}`);

            For identifiers use sql.identifier(name) with a value from a fixed allow-list.
        """,
        "postgres-js": """
            Use the tagged template (values become parameters):

              await sql`SELECT ... WHERE email = ${email}`;

            or sql.unsafe("SELECT ... WHERE email = $1", [email]); identifiers: ${sql(columnName)}.
        """,
        "knex": """
            knex.raw("SELECT ... WHERE email = ?", [email]);      // ?? for identifiers
            .whereRaw("lower(email) = ?", [email])
        """,
        "psycopg": """
            Pass values as parameters (never with %):

              cur.execute("SELECT ... WHERE email = %s AND org_id = %s", (email, org_id))

            Identifiers: psycopg.sql.SQL("SELECT * FROM {}").format(sql.Identifier(table))
            (psycopg2: from psycopg2 import sql).
        """,
        "asyncpg": """
            await conn.fetch("SELECT ... WHERE email = $1 AND org_id = $2", email, org_id)
        """,
        "sqlalchemy": """
            session.execute(text("SELECT ... WHERE email = :email"), {"email": email})

            or build the query with select(...).where(User.email == email).
        """,
        "django": """
            User.objects.raw("SELECT ... WHERE email = %s", [email])
            cursor.execute("SELECT ... WHERE email = %s", [email])

            or use the ORM: User.objects.filter(email=email).
        """,
    },
)

# ---------------------------------------------------------------- PGL012
_rule(
    "PGL012",
    "Database client or pool created per request",
    """
Opening a PostgreSQL connection costs a TCP (usually TLS) handshake, authentication and a new
server process, which is milliseconds of latency and megabytes of server memory each time. A
pool or ORM client created inside a request handler opens fresh connections on every request,
and if it is not closed they pile up until the server hits max_connections ("sorry, too many
clients already") and every request fails. Create one pool per process and reuse it.
""",
    {
        "node-pg": """
            // db.ts: one pool per process
            import { Pool } from "pg";
            export const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 10 });

            // in the handler: borrow a connection for one query
            const { rows } = await pool.query("SELECT ... WHERE id = $1", [id]);
        """,
        "prisma": """
            // lib/prisma.ts: one client per process (and one across Next.js dev hot reloads)
            import { PrismaClient } from "@prisma/client";
            const globalForPrisma = globalThis as unknown as { prisma?: PrismaClient };
            export const prisma = globalForPrisma.prisma ?? new PrismaClient();
            if (process.env.NODE_ENV !== "production") globalForPrisma.prisma = prisma;
        """,
        "postgres-js": """
            // db.ts: one instance per process
            import postgres from "postgres";
            export const sql = postgres(process.env.DATABASE_URL!, { max: 10 });
        """,
        "sqlalchemy": """
            # db.py: one engine per process
            engine = create_engine(DATABASE_URL, pool_size=10, max_overflow=5, pool_pre_ping=True)
            SessionLocal = sessionmaker(engine)

            # per request:
            with SessionLocal() as session:
                ...
        """,
        "psycopg": """
            # db.py: one pool per process
            from psycopg_pool import ConnectionPool
            pool = ConnectionPool(DATABASE_URL, min_size=1, max_size=10)

            # per request:
            with pool.connection() as conn:
                conn.execute("SELECT ...", (value,))
        """,
        "asyncpg": """
            # at startup (e.g. FastAPI lifespan):
            app.state.pool = await asyncpg.create_pool(DATABASE_URL, max_size=10)

            # per request:
            async with request.app.state.pool.acquire() as conn:
                await conn.fetch("SELECT ... WHERE id = $1", id)
        """,
    },
)

# ---------------------------------------------------------------- PGL013
_rule(
    "PGL013",
    "Query inside a loop over rows (N+1)",
    """
A query inside a loop over rows you already fetched sends one round trip per row: one query
for the list plus N for the related data. Each round trip costs network latency plus parse and
plan time, so a page that is fast with 10 rows takes seconds with 1,000 and holds a pooled
connection the whole time. Fetch the related rows in one query: a join, an include or eager
load, or WHERE id = ANY($1).
""",
    {
        "prisma": """
            Load the relation with the list:

              const rows = await prisma.<model>.findMany({ include: { <relation>: true } });

            or fetch all related rows in one query and join them in memory:

              const related = await prisma.<target>.findMany({ where: { id: { in: rows.map((r) => r.<key>) } } });
        """,
        "drizzle": """
            Use a relational query or one IN query:

              const rows = await db.query.<model>.findMany({ with: { <relation>: true } });
              // or
              const related = await db.select().from(<target>).where(inArray(<target>.id, rows.map((r) => r.<key>)));
        """,
        "node-pg": """
            Fetch all related rows in one query, then group them in JavaScript:

              const { rows: related } = await pool.query(
                "SELECT ... FROM <target> WHERE id = ANY($1)", [rows.map((r) => r.<key>)]);

            or JOIN them into the first query.
        """,
        "sqlalchemy": """
            Eager-load the relationship in the first query:

              stmt = select(<model>).options(selectinload(<model>.<relation>))   # or joinedload for many-to-one

            or fetch the related rows once: select(<target>).where(<target>.id.in_(ids)).
        """,
        "django": """
            Load it with the first query:

              <model>.objects.select_related("<relation>")     # ForeignKey / OneToOne
              <model>.objects.prefetch_related("<relation>")   # reverse FK / ManyToMany

            or fetch them once: <target>.objects.in_bulk(ids).
        """,
        "django-fk": """
            Join it into the first query:

              <model>.objects.select_related("<relation>")
        """,
        "django-rev": """
            Load all of them with one extra query instead of one per row:

              <model>.objects.prefetch_related("<relation>")
        """,
        "psycopg": """
            Fetch all related rows in one query (psycopg adapts a list to an array):

              cur.execute("SELECT ... FROM <target> WHERE id = ANY(%s)", (ids,))
        """,
        "asyncpg": """
            await conn.fetch("SELECT ... FROM <target> WHERE id = ANY($1::bigint[])", ids)
        """,
    },
    heuristic=True,
)

# ---------------------------------------------------------------- PGL014
_rule(
    "PGL014",
    "Unbounded query in a request handler",
    """
A list query with no LIMIT returns every matching row. It is fast with test data and grows
with the table: response size, memory and query time grow without bound, and one large account
can make the endpoint time out. Cap every list endpoint and paginate.
""",
    {
        "prisma": """
            const rows = await prisma.<model>.findMany({ ..., take: 50, orderBy: { id: "asc" } });
            // next page: add cursor: { id: lastId }, skip: 1
        """,
        "drizzle": """
            await db.select().from(<model>).where(...).orderBy(asc(<model>.id)).limit(50);
        """,
        "sql": """
            SELECT ... ORDER BY id LIMIT 50;   -- next page: WHERE id > $last ORDER BY id LIMIT 50
        """,
        "sqlalchemy": """
            session.scalars(select(<model>).where(...).order_by(<model>.id).limit(50)).all()
        """,
        "django": """
            <model>.objects.filter(...).order_by("id")[:50]
            (or a Paginator / DRF pagination_class on the view)
        """,
    },
    heuristic=True,
)

# ---------------------------------------------------------------- PGL015
_rule(
    "PGL015",
    "OFFSET pagination",
    """
OFFSET n makes PostgreSQL produce and throw away n rows before returning the page, so the cost
of a page grows with its depth (page 1,000 reads 1,000 pages of rows) and rows shift between
pages while data changes. Keyset (cursor) pagination, WHERE (sort_key, id) > (last values)
ORDER BY sort_key, id LIMIT n, uses an index and costs the same on every page. Fine for small
tables and admin screens; worth changing for public, deep or infinite-scroll lists.
""",
    {
        "prisma": """
            const page = await prisma.<model>.findMany({
              take: 20, skip: lastId ? 1 : 0, cursor: lastId ? { id: lastId } : undefined, orderBy: { id: "asc" },
            });
        """,
        "drizzle": """
            await db.select().from(<model>).where(gt(<model>.id, lastId)).orderBy(asc(<model>.id)).limit(20);
        """,
        "sql": """
            SELECT ... WHERE (created_at, id) < ($1, $2) ORDER BY created_at DESC, id DESC LIMIT 20;
            -- with an index on (created_at, id)
        """,
        "sqlalchemy": """
            select(<model>).where(<model>.id > last_id).order_by(<model>.id).limit(20)
        """,
        "django": """
            <model>.objects.filter(id__gt=last_id).order_by("id")[:20]
        """,
    },
)

