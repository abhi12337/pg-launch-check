# ---------------------------------------------------------------- PGL019
_rule(
    "PGL019",
    "No statement timeout on the database client",
    """
Without a statement timeout a slow query (a missing index, a lock wait, an accidental full
scan) runs until it finishes: it holds a pooled connection the whole time, the HTTP request
gives up long before the database does, and retries stack more copies of the same query on
top. A server-side statement_timeout makes PostgreSQL cancel it.
""",
    {
        "node-pg": """
            new Pool({ connectionString, max: 10, statement_timeout: 15_000, idle_in_transaction_session_timeout: 30_000 })
        """,
        "postgres-js": """
            postgres(url, { max: 10, connection: { statement_timeout: 15000 } })   // sent as a startup parameter
        """,
        "sqlalchemy": """
            create_engine(url, connect_args={"options": "-c statement_timeout=15000"})          # psycopg / psycopg2
            create_async_engine(url, connect_args={"server_settings": {"statement_timeout": "15000"}})   # asyncpg
        """,
        "asyncpg": """
            await asyncpg.create_pool(url, max_size=10, command_timeout=15,
                                      server_settings={"statement_timeout": "15000"})
        """,
        "psycopg": """
            psycopg.connect(url, options="-c statement_timeout=15000")
            ConnectionPool(url, max_size=10, kwargs={"options": "-c statement_timeout=15000"})
        """,
        "default": """
            Or set it for the app's database role (works for every client, and behind PgBouncer or
            Supavisor in transaction mode, which may reject startup parameters):

              ALTER ROLE app_user SET statement_timeout = '15s';
        """,
    },
)

# ---------------------------------------------------------------- PGL020
_rule(
    "PGL020",
    "Serverless functions connecting without a pooler hint",
    """
Serverless platforms run many short-lived instances, and each one that creates its own pool
opens its own connections, so a traffic spike becomes hundreds of connections and exhausts
max_connections. A connection pooler (PgBouncer, Supavisor, Neon's pooled endpoint, RDS Proxy,
Prisma Accelerate) multiplexes them. This tool cannot see the DATABASE_URL your deployment
uses, so treat this as a reminder to check, not as proof of a problem.
""",
    {
        "default": """
            Point the app at the pooled connection string and keep the per-instance pool small:
              - Supabase: the Supavisor transaction-mode URL (port 6543)
              - Neon: the host with -pooler in its name
              - Prisma: add ?pgbouncer=true&connection_limit=1 to the pooled URL, and set
                directUrl (a direct connection) in the datasource for migrations
              - node-postgres / postgres.js: max: 1-5 per instance
            On Vercel Fluid compute, also look at attachDatabasePool from @vercel/functions.
        """,
    },
)


@dataclass
class Finding:
    rule_id: str
    severity: str
    message: str
    file: str | None = None
    line: int | None = None
    evidence: str | None = None
    heuristic: bool = False
    extra: dict = field(default_factory=dict)

    @property
    def rule(self) -> Rule:
        return RULES[self.rule_id]

    @property
    def location(self) -> str:
        if self.file is None:
            return ""
        return f"{self.file}:{self.line}" if self.line else self.file

    @property
    def fix(self) -> str:
        """The fix for this finding's stack, with its names filled in."""
        fixes = self.rule.fixes
        keys = self.extra.get("fixkeys", [])
        parts = [fixes[k] for k in keys if k in fixes]
        if not parts:
            parts = [fixes.get("default") or self.rule.fix]
        elif "default" in fixes and self.extra.get("with_default"):
            parts.append(fixes["default"])
        text = "\n\n".join(parts[:2])
        e = self.extra
        subs = {
            "<table>": e.get("table") or "your_table",
            "<cols>": ", ".join(e.get("cols") or []) or e.get("col") or "column",
            "<col>": e.get("col") or "column",
            "<index>": e.get("index") or "your_index",
            "<constraint>": e.get("constraint") or "your_constraint",
            "<constraint_src>": e.get("constraint_src") or "CONSTRAINT ...",
            "<type>": e.get("type") or "new_type",
            "<default>": e.get("default") or "...",
            "<value>": e.get("value") or "...",
            "<unique>": "UNIQUE " if e.get("unique") else "",
            "<model>": e.get("model") or "Model",
            "<fields>": ", ".join(e.get("fields") or []) or "field",
            "<field>": e.get("field") or "field",
            "<relation>": e.get("relation") or "relation",
            "<target>": e.get("target") or "related_table",
            "<key>": e.get("key") or "relatedId",
            "<recv>": e.get("recv") or "pool",
            "<stmt>": e.get("stmt") or "CREATE INDEX CONCURRENTLY ... ;   -- same definition",
        }
        for k, v in subs.items():
            text = text.replace(k, v)
        return text

    def to_dict(self) -> dict:
        d = asdict(self)
        d["title"] = self.rule.title
        d["why"] = self.rule.why
        d["fix"] = self.fix
        extra = {k: v for k, v in d.pop("extra").items() if k not in ("fixkeys", "with_default")}
        if extra:
            d["extra"] = extra
        return d


def sort_findings(findings: list[Finding]) -> list[Finding]:
    return sorted(findings, key=lambda f: (SEVERITY_RANK[f.severity], f.rule_id, f.file or "", f.line or 0))


def clip_line(line: str, limit: int = 160) -> str:
    s = line.strip()
    return s if len(s) <= limit else s[: limit - 3] + "..."


